"""LaTeX tables for the report from the committed result files (CLAUDE.md §0 rule 11).

    python -m experiments.report_tables [--out report/tables]

Reads only files under experiments/results/ and bench/results/ that the E-scripts wrote at a
tagged commit, aggregates them (means over runs, counts of runs above α), and writes one .tex
table per file into --out, each with a comment naming its source files. The chapters \\input
these files; no number is typed by hand.
"""

from __future__ import annotations

import argparse
import collections
import csv
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "experiments" / "results"
GATE_NAMES = {"G0": "no gate", "G1": "residual percentile (DeepOHeat-v2)",
              "G2": "split conformal", "G3": "weighted conformal",
              "G4": "ACI, flagged labels only", "G5": "audited ACI",
              "G6": "audited multivalid", "G7": "audited ACI, risk-adaptive"}


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _alpha(rows: list[dict[str, str]]) -> float:
    a = {float(r["alpha"]) for r in rows}
    if len(a) != 1:
        raise ValueError(f"runs disagree on alpha: {a}")
    return a.pop()


def gate_table(folder: str, caption: str, label: str) -> str:
    src = RES / folder / "e7_runs.csv"
    R = _rows(src)
    alpha = _alpha(R)
    agg = collections.defaultdict(list)
    for r in R:
        agg[(r["gate"], r["p"] if r["gate"] == "G5" else "")].append(r)
    L = [f"% generated by experiments/report_tables.py from {src.relative_to(ROOT).as_posix()}",
         r"\begin{table}[t]\centering\small", r"\begin{tabular}{llrrrr}", r"\hline",
         r"Gate & & $p$ & mean $M_1$ & runs with $M_1>\alpha$ & exact solves / proposal \\",
         r"\hline"]
    for (g, p), v in sorted(agg.items()):
        m1 = st.mean(float(r["M1_all"]) for r in v)
        ex = sum(float(r["M1_all"]) > alpha for r in v)
        sv = st.mean(int(r["solves"]) / int(r["T"]) for r in v)
        L.append(f"{g} & {GATE_NAMES[g]} & {p or '--'} & {m1:.4f} & {ex}/{len(v)} & {sv:.3f} \\\\")
    L += [r"\hline", r"\end{tabular}",
          f"\\caption{{{caption} $\\alpha = {alpha:g}$; {len(R)} runs in all, 45 per row "
          "(P1--P3 $\\times$ 3 aggressiveness levels $\\times$ 5 seeds).}",
          f"\\label{{{label}}}", r"\end{table}"]
    return "\n".join(L) + "\n"


def group_table(folder: str, caption: str, label: str) -> str:
    src = RES / folder / "e15_groups.csv"
    R = _rows(src)
    alpha = _alpha(R)
    agg = collections.defaultdict(lambda: [0, 0])
    for r in R:
        k = (r["gate"], r["group"])
        agg[k][0] += 1
        agg[k][1] += float(r["M1g"]) > alpha
    groups = sorted({g for _, g in agg})
    L = [f"% generated by experiments/report_tables.py from {src.relative_to(ROOT).as_posix()}",
         r"\begin{table}[t]\centering\small", r"\begin{tabular}{lrr}", r"\hline",
         r"Group & G5: runs with $M_{1,g}>\alpha$ & G6: runs with $M_{1,g}>\alpha$ \\", r"\hline"]
    for g in groups:
        a, b = agg[("G5", g)], agg[("G6", g)]
        L.append(f"{g.replace('_', chr(92) + '_')} & {a[1]}/{a[0]} & {b[1]}/{b[0]} \\\\")
    L += [r"\hline", r"\end{tabular}", f"\\caption{{{caption} $\\alpha = {alpha:g}$.}}",
          f"\\label{{{label}}}", r"\end{table}"]
    return "\n".join(L) + "\n"


def audit_table(folder: str, caption: str, label: str) -> str:
    src = RES / folder / "e16_runs.csv"
    R = _rows(src)
    alpha = _alpha(R)
    agg = collections.defaultdict(list)
    for r in R:
        agg[(r["gate"], r["p"], r["p_min"])].append(r)
    L = [f"% generated by experiments/report_tables.py from {src.relative_to(ROOT).as_posix()}",
         r"\begin{table}[t]\centering\small", r"\begin{tabular}{lrrrrr}", r"\hline",
         r"Gate & $\bar p$ & $p_{\min}$ & audits / run & mean $M_1$ & runs with $M_1>\alpha$ \\",
         r"\hline"]
    for (g, p, pm), v in sorted(agg.items()):
        L.append(f"{g} & {p} & {pm or '--'} & {st.mean(int(r['audited']) for r in v):.1f} & "
                 f"{st.mean(float(r['M1_all']) for r in v):.4f} & "
                 f"{sum(float(r['M1_all']) > alpha for r in v)}/{len(v)} \\\\")
    L += [r"\hline", r"\end{tabular}", f"\\caption{{{caption} $\\alpha = {alpha:g}$.}}",
          f"\\label{{{label}}}", r"\end{table}"]
    return "\n".join(L) + "\n"


def e4_table() -> str:
    src = ROOT / "bench" / "results" / "pipeline_bench.csv"
    R = _rows(src)
    meta = json.loads(src.with_suffix(".json").read_text(encoding="utf-8"))
    seq = next(r for r in R if r["mode"] == "sequential_cpu")
    L = [f"% generated by experiments/report_tables.py from {src.relative_to(ROOT).as_posix()}",
         r"\begin{table}[t]\centering\small", r"\begin{tabular}{lrrrr}", r"\hline",
         r"Pipeline & batch & certified designs/s & speed-up & mean PCG iterations \\", r"\hline",
         f"sequential CPU loop & 1 & {float(seq['designs_per_s']):.3f} & 1.0 & "
         f"{float(seq['mean_iters']):.0f} \\\\"]
    for r in R:
        if r["mode"] == "sequential_cpu":
            continue
        sp = float(r["designs_per_s"]) / float(seq["designs_per_s"])
        L.append(f"batched GPU & {r['batch']} & {float(r['designs_per_s']):.3f} & {sp:.1f} & "
                 f"{float(r['mean_iters']):.0f} \\\\")
    L += [r"\hline", r"\end{tabular}",
          f"\\caption{{E4: certified designs per second at $\\tau_v = {meta['tau_v']:g}$~K "
          f"({meta['n_boards']} test boards, {meta['dtype']} iterations; GPU rate includes "
          "host-device transfers). H5: "
          f"{'passed' if meta['H5']['passed'] else 'not passed'}.}}",
          r"\label{tab:e4}", r"\end{table}"]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "report" / "tables")
    a = ap.parse_args(argv)
    a.out.mkdir(parents=True, exist_ok=True)
    jobs = {
        "e7_tau1.tex": gate_table("e7", r"E7 at the pre-registered $\tau = 1$~K (tag v3-freeze).",
                                  "tab:e7-tau1"),
        "e7_tau02.tex": gate_table("e7_tau0.2", r"E7 at the sensitivity $\tau = 0.2$~K "
                                   "(tag v3.1-freeze, D4 amendment).", "tab:e7-tau02"),
        "e15_tau02.tex": group_table("e15_tau0.2", r"E15 per-group accepted-error rate at "
                                     r"$\tau = 0.2$~K, $p = 0.1$.", "tab:e15-tau02"),
        "e16_tau02.tex": audit_table("e16_tau0.2", r"E16 risk-adaptive audits (G7) against "
                                     r"uniform audits (G5) at $\tau = 0.2$~K.", "tab:e16-tau02"),
        "e4.tex": e4_table(),
    }
    for name, text in jobs.items():
        (a.out / name).write_text(text, encoding="utf-8")
        print(f"wrote {a.out / name}")


if __name__ == "__main__":
    main()
