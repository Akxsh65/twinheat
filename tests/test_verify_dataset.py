"""Independent dataset verification (N2.2; CLAUDE.md §5 B2/B3 and data hygiene).

Tiny datasets (N = 16, a few boards, CPU) generated by data/generate.py; each test breaks one
thing and checks that data/verify_dataset.py reports it and exits non-zero.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from data import generate as gen
from data import verify_dataset as vd

N, COUNT, SHARD = 16, 6, 3
KW = {"N": N, "shard_size": SHARD, "batch": 3, "device": "cpu", "allow_dirty": True,
      "log": lambda *a, **k: None}
VKW = {"resolve_frac": 1.0, "phi_N": 16, "allow_dirty": True, "make_figures": False}


@pytest.fixture(scope="module")
def dataset(tmp_path_factory) -> Path:
    root = tmp_path_factory.mktemp("dataset")
    gen.generate("val", COUNT, 3, root / "val", **KW)
    gen.generate("ood_6", COUNT, 3, root / "ood_6", **KW)
    return root


def _copy(src: Path, dst: Path) -> Path:
    import shutil

    shutil.copytree(src, dst)
    return dst


def _rehash(split_dir: Path) -> None:
    """Rewrite the manifest's file hashes after a deliberate edit (simulates a consistent fake)."""
    man = json.loads((split_dir / "manifest.json").read_text(encoding="utf-8"))
    for sh in man["shards"]:
        sh["files"] = {f: gen._sha256(split_dir / sh["name"] / f) for f in sh["files"]}
    (split_dir / "manifest.json").write_text(json.dumps(man, indent=2, sort_keys=True),
                                             encoding="utf-8")


def test_clean_dataset_passes_and_reports_every_split(dataset, tmp_path) -> None:
    rep = vd.verify_dataset(dataset, report=tmp_path / "report.md", **VKW)
    assert rep.failures == [], rep.failures
    assert set(rep.splits) == {"val", "ood_6"}
    for s in rep.splits.values():
        assert s.count == COUNT and s.resolved == COUNT and s.worst_rel_err < vd.FIELD_TOL
        assert len(s.mean_phi) == 4 and sum(s.chip_hist.values()) == COUNT
    text = (tmp_path / "report.md").read_text(encoding="utf-8")
    assert "PASS" in text and "val" in text and "ood_6" in text


def test_cli_exit_codes(dataset, tmp_path) -> None:
    args = ["--root", str(dataset), "--resolve-frac", "1", "--phi-N", "16", "--allow-dirty",
            "--no-figures", "--report", str(tmp_path / "r.md")]
    assert vd.main(args) == 0
    bad = _copy(dataset, tmp_path / "bad")
    f = bad / "val" / "shard_0000" / "fields.npy"
    f.write_bytes(f.read_bytes()[:-2] + b"\x00\x00")
    assert vd.main([*args[:1], str(bad), *args[2:]]) == 1


def test_tampered_file_fails_the_hash_check(dataset, tmp_path) -> None:
    bad = _copy(dataset, tmp_path / "ds")
    f = bad / "val" / "shard_0001" / "records.jsonl"
    f.write_bytes(f.read_bytes() + b" ")
    rep = vd.verify_dataset(bad, **VKW)
    assert any("val" in m and "SHA-256" in m for m in rep.failures)


def test_wrong_stored_field_fails_the_resolve_check(dataset, tmp_path) -> None:
    bad = _copy(dataset, tmp_path / "ds")
    f = bad / "ood_6" / "shard_0000" / "fields.npy"
    a = np.load(f)
    a[0] = (a[0].astype(np.float32) * 1.01).astype(np.float16)  # 1 % off, hashes kept consistent
    np.save(f, a, allow_pickle=False)
    _rehash(bad / "ood_6")
    rep = vd.verify_dataset(bad, **VKW)
    assert any("ood_6" in m and "re-solve" in m for m in rep.failures), rep.failures


def test_edited_record_fails_its_record_hash(dataset, tmp_path) -> None:
    bad = _copy(dataset, tmp_path / "ds")
    f = bad / "val" / "shard_0000" / "records.jsonl"
    rows = f.read_text(encoding="utf-8").splitlines()
    row = json.loads(rows[0])
    row["record"]["chips"][0]["P"] *= 2  # changed record, stale record_sha256
    rows[0] = json.dumps(row, sort_keys=True)
    f.write_text("\n".join(rows) + "\n", encoding="utf-8")
    _rehash(bad / "val")
    rep = vd.verify_dataset(bad, **VKW)
    assert any("record_sha256" in m for m in rep.failures), rep.failures


def test_same_record_in_two_splits_is_caught() -> None:
    dups = vd.cross_split_duplicates({"val": {"a", "b"}, "test": {"c"}, "cal": {"b", "d"}})
    assert dups == {"b": ["cal", "val"]}
    assert vd.cross_split_duplicates({"val": {"a"}, "test": {"b"}}) == {}


def test_provenance_rules() -> None:
    good = {"commit": "abc1234", "spec_sha256": vd.current_spec_hashes(), "complete": True}
    assert vd.provenance_problems(good, allow_dirty=False) == []
    assert any("dirty" in p for p in vd.provenance_problems({**good, "commit": "abc-dirty"},
                                                            allow_dirty=False))
    assert vd.provenance_problems({**good, "commit": "abc-dirty"}, allow_dirty=True) == []
    changed = {**good, "spec_sha256": {**good["spec_sha256"], "config/spec_v2.yaml": "0" * 64}}
    assert any("spec_v2.yaml" in p for p in vd.provenance_problems(changed, allow_dirty=True))
    assert any("incomplete" in p for p in vd.provenance_problems({**good, "complete": False},
                                                                 allow_dirty=True))


